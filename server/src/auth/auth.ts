import { betterAuth } from "better-auth";
import type { Pool } from "pg";
import type { ServerConfig } from "../config/env.ts";
import {
  emailLocale,
  type TransactionalEmailService,
  type EmailKind,
} from "../email/service.ts";

export type AuthConfig = Pick<
  ServerConfig,
  "nodeEnv" | "betterAuthSecret" | "betterAuthUrl"
> &
  Partial<Pick<ServerConfig, "emailMode" | "publicAppUrl">>;

export interface AuthOptions {
  developmentProvisioning?: true;
  // Private server API instance only; its handler is never attached to HTTP.
  invitationRegistration?: true;
  email?: TransactionalEmailService;
  emailTasks?: { submit(work: () => Promise<void>): void };
}

export function trustedApplicationOrigins(
  config: Pick<AuthConfig, "nodeEnv" | "betterAuthUrl" | "publicAppUrl">,
) {
  return [
    new URL(config.betterAuthUrl).origin,
    ...(config.publicAppUrl && config.publicAppUrl !== config.betterAuthUrl
      ? [config.publicAppUrl]
      : []),
    ...(config.nodeEnv === "development" ? ["http://127.0.0.1:5173"] : []),
  ];
}

// The provisioning instance is created only by an explicit local CLI command.
// The HTTP server always uses the default instance with registration disabled.
export function createAuth(
  pool: Pool,
  config: AuthConfig,
  {
    developmentProvisioning,
    invitationRegistration,
    email,
    emailTasks,
  }: AuthOptions = {},
) {
  if (developmentProvisioning && config.nodeEnv !== "development") {
    throw new Error("Account provisioning requires NODE_ENV=development.");
  }
  const secureCookies =
    config.nodeEnv === "production" ||
    new URL(config.betterAuthUrl).protocol === "https:";
  const verificationRequired = email?.enabled === true;
  const appOrigin = config.publicAppUrl ?? config.betterAuthUrl;
  const send = (
    kind: EmailKind,
    user: { email: string },
    url: string,
    request?: Request,
  ) => {
    if (!email?.enabled || !emailTasks)
      throw new Error("Email delivery configuration unavailable.");
    const link = new URL(url);
    if (link.origin !== new URL(config.betterAuthUrl).origin)
      throw new Error("Untrusted auth email origin.");
    // Only paths/tokens generated by Better Auth; host comes from server config.
    const trusted = new URL(link.pathname + link.search, appOrigin).href;
    const callback = new URL(
      link.searchParams.get("callbackURL") ?? "/",
      appOrigin,
    );
    const locale = emailLocale(
      request?.headers.get("x-budograph-locale") ??
        callback.searchParams.get("lang"),
    );
    emailTasks.submit(() =>
      email.send({ kind, to: user.email, url: trusted, locale }),
    );
  };

  return betterAuth({
    appName: "BudoGraph",
    database: pool,
    secret: config.betterAuthSecret,
    baseURL: config.betterAuthUrl,
    basePath: "/api/auth",
    trustedOrigins: trustedApplicationOrigins(config),
    disabledPaths: ["/sign-up/email"],
    emailAndPassword: {
      enabled: true,
      disableSignUp: !developmentProvisioning && !invitationRegistration,
      autoSignIn: false,
      requireEmailVerification: verificationRequired,
      resetPasswordTokenExpiresIn: 3600,
      revokeSessionsOnPasswordReset: true,
      ...(verificationRequired
        ? {
            sendResetPassword: async ({ user, url }, request) => {
              send("reset", user, url, request);
            },
          }
        : {}),
    },
    emailVerification: {
      expiresIn: 3600,
      sendOnSignUp: verificationRequired,
      sendOnSignIn: false,
      autoSignInAfterVerification: false,
      ...(verificationRequired
        ? {
            sendVerificationEmail: async ({ user, url }, request) => {
              send("verification", user, url, request);
            },
          }
        : {}),
    },
    user: {
      additionalFields: {
        active: {
          type: "boolean",
          required: true,
          defaultValue: true,
          input: false,
        },
      },
    },
    databaseHooks: {
      session: {
        create: {
          before: async (session) => {
            const result = await pool.query<{
              active: boolean;
              emailVerified: boolean;
            }>(
              verificationRequired
                ? 'SELECT active,"emailVerified" FROM public."user" WHERE id = $1'
                : 'SELECT active FROM public."user" WHERE id = $1',
              [session.userId],
            );
            if (result.rows[0]?.active !== true) return false;
            if (verificationRequired && result.rows[0]?.emailVerified !== true)
              return false;
          },
        },
      },
    },
    session: {
      cookieCache: { enabled: false },
    },
    advanced: {
      // Tests without PostgreSQL exercise HTTP/session boundaries separately;
      // real runtime instances validate the migrated schema read-only.
      database: { validateSchema: config.nodeEnv !== "test" },
      useSecureCookies: secureCookies,
      defaultCookieAttributes: {
        httpOnly: true,
        sameSite: "lax",
        secure: secureCookies,
      },
      // The HTTP adapter overwrites this header with the direct peer IP.
      ipAddress: { ipAddressHeaders: ["x-budograph-client-ip"] },
    },
    rateLimit: {
      enabled: true,
      storage: "memory",
    },
    // Library diagnostics can include DB errors, cookies or request bodies.
    // Fastify records static safe messages at the surrounding boundary.
    logger: { disabled: true },
    telemetry: { enabled: false },
  });
}

export type Auth = ReturnType<typeof createAuth>;
